-- [[ Generate VSCode Which Key menu from nvim leader keymaps ]]
--  Builds `whichkey.bindings` for the VSpaceCode.whichkey extension in Cursor
--  from the leader keymaps nvim defines in vscode mode (`lua/vscode-keymaps.lua`).
--  Each entry sends the original keys back to nvim, so the Lua keymap stays
--  the single source of truth. Group names come from the which-key.nvim spec.
--
--  Usage (rerun after changing keymaps):
--    nvim -l scripts/vscode-whichkey.lua

local config_dir = vim.fn.fnamemodify(debug.getinfo(1, 'S').source:sub(2), ':p:h:h')
local settings_path = vim.fn.expand '~/Library/Application Support/Cursor/User/settings.json'
local start_marker, end_marker = '// whichkey:start', '// whichkey:end'

-- Load the config in vscode mode in a child nvim and dump its leader keymaps.
-- `vscode` only exists inside vscode-neovim, so stub it out.
local dump = [[
local maps = {}
for _, m in ipairs(vim.api.nvim_get_keymap 'n') do
  if m.lhs:sub(1, 1) == ' ' then table.insert(maps, { lhs = m.lhs, desc = m.desc or m.rhs or '' }) end
end
local groups = {}
for _, s in ipairs(require('plugins.editor.which-key')[1].opts.spec) do
  groups[(s[1]:gsub('<leader>', ' '))] = s.group
end
io.stdout:write('WHICHKEY_JSON:' .. vim.json.encode { maps = maps, groups = groups } .. '\n')
]]
local result = vim.system({
  'nvim', '--headless',
  '--cmd', 'let g:vscode = 1',
  '--cmd', 'lua package.preload.vscode = function() return {} end',
  '+lua ' .. dump:gsub('\n', ' '),
  '+qa',
}, { cwd = config_dir, text = true }):wait()
local json = (result.stdout or ''):match 'WHICHKEY_JSON:(.-)\n'
assert(json, 'Failed to read keymaps from nvim:\n' .. (result.stderr or ''))
local data = vim.json.decode(json)

-- Strip which-key style [B]racket hints: '[S]earch [F]iles' -> 'Search Files', '[/] Search' -> 'Search'
local clean = function(desc) return (desc:gsub('^%[[^%]]*%]%s+', ''):gsub('%[(.-)%]', '%1')) end

-- Split an lhs into keys, keeping <...> keycodes together
local split_keys = function(lhs)
  local keys, i = {}, 1
  while i <= #lhs do
    local key = lhs:match('^<[^>]+>', i) or lhs:sub(i, i)
    table.insert(keys, key)
    i = i + #key
  end
  return keys
end

-- Build a tree keyed by each key after <leader>
local root = { children = {} }
for _, m in ipairs(data.maps) do
  local node, prefix = root, ' '
  local keys = split_keys(m.lhs:sub(2))
  for i, key in ipairs(keys) do
    prefix = prefix .. key
    node.children[key] = node.children[key] or { key = key, prefix = prefix, children = {} }
    node = node.children[key]
    if i == #keys then node.map = m end
  end
end

-- Send keys back to nvim with keycodes it understands
local to_input = function(lhs) return (lhs:gsub('<', '<LT>'):gsub(' ', '<Space>')) end

local sorted = function(children)
  local list = vim.tbl_values(children)
  table.sort(list, function(a, b)
    if a.key:lower() ~= b.key:lower() then return a.key:lower() < b.key:lower() end
    return a.key > b.key -- lowercase before uppercase
  end)
  return list
end

local encode
local leaf = function(key, map, pad)
  return ('%s{ "key": %s, "name": %s, "type": "command", "command": "vscode-neovim.send", "args": %s }'):format(
    pad, vim.json.encode(key), vim.json.encode(clean(map.desc)), vim.json.encode(to_input(map.lhs)))
end
encode = function(children, depth)
  local pad = string.rep('    ', depth)
  local items = {}
  for _, node in ipairs(sorted(children)) do
    if vim.tbl_isempty(node.children) then
      table.insert(items, leaf(node.key, node.map, pad))
    else
      local inner = encode(node.children, depth + 2)
      -- A key that is both a keymap and a prefix (e.g. <leader>b and <leader>bd):
      -- whichkey can't do both, so the keymap moves inside the group under the same key
      if node.map then inner = leaf(node.key, node.map, string.rep('    ', depth + 2)) .. ',\n' .. inner end
      local name = data.groups[node.prefix] and clean(data.groups[node.prefix]) or node.key
      table.insert(items, ('%s{\n%s    "key": %s,\n%s    "name": %s,\n%s    "type": "bindings",\n%s    "bindings": [\n%s\n%s    ]\n%s}'):format(
        pad, pad, vim.json.encode(node.key), pad, vim.json.encode('+' .. name), pad, pad, inner, pad, pad))
    end
  end
  return table.concat(items, ',\n')
end

local block = ('%s (generated by nvim scripts/vscode-whichkey.lua, do not edit)\n    "whichkey.bindings": [\n%s\n    ]\n    %s'):format(
  start_marker, encode(root.children, 2), end_marker)

-- Replace the generated block in settings.json, or append it as the last entry
local file = assert(io.open(settings_path, 'r'))
local settings = file:read '*a'
file:close()
local s, e = settings:find(vim.pesc(start_marker) .. '.-' .. vim.pesc(end_marker))
if s then
  settings = settings:sub(1, s - 1) .. block .. settings:sub(e + 1)
else
  settings = settings:gsub('%s*}%s*$', function() return ',\n\n    ' .. block .. '\n}\n' end)
end
file = assert(io.open(settings_path, 'w'))
file:write(settings)
file:close()

print(('Wrote %d leader keymaps to %s'):format(#data.maps, settings_path))

